"""Regenerate Task 23's numeric report from validated retained raw data."""
import json
from pathlib import Path

from fit_gustafson import fit, load_results

ROOT = Path(__file__).resolve().parents[1]


def main():
    summary = load_results(ROOT / "benchmarks" / "results.csv")
    result = fit(summary)
    meta = json.loads((ROOT / "benchmarks" / "results.metadata.json").read_text(encoding="utf-8"))
    if meta["status"] != "complete":
        raise ValueError("Cannot report an incomplete benchmark session")
    lines = ["# Task 23 — Experimental results", "",
             "**Ayazgaliyev Aibek · 230103341**", "",
             f"I measured {sum(r['runs'] for r in summary)} real trials across {len(summary)} worker counts, "
             f"with {summary[0]['runs']} trials per count and {summary[0]['k']:,} integration points per worker. "
             "Each parallel trial started fresh processes; I retained every observation.", "",
             f"Session: **{meta['started_at']}** to **{meta['finished_at']}**. "
             "The timestamps include the local UTC offset.", "",
             "## Measurements", "",
             "P is the worker count, k is points per worker, Ts is direct serial time, and Tp is "
             "startup-inclusive parallel time for the same P × k points. I averaged the paired "
             "speedup ratios, not the timing means.", "",
             "```text", "Speedup S = Ts / Tp", "Scaled efficiency E = S / P",
             "Standard error SE = SD / √5", "```", "",
             "Times below are means in seconds. SD uses the sample denominator n − 1. "
             "The speedup uncertainty is ±1 SE, not a 95% confidence interval.", "",
             "| P | Tp (s) | Ts (s) | Speedup ± SE | Efficiency |",
             "|---:|---:|---:|---:|---:|"]
    for row in summary:
        lines.append(f"| {row['P']} | {row['mean_parallel_seconds']:.6f} | {row['mean_serial_seconds']:.6f} | "
                     f"{row['mean_scaled_speedup']:.6f} ± {row['se_scaled_speedup']:.6f} | "
                     f"{100*row['mean_scaled_efficiency']:.4f}% |")
    lines += ["", "## Least-squares derivation", "",
              "I fitted the mean speedup y at each P by minimizing the unweighted squared errors. "
              "Here Σ means summing over the 12 worker counts.", "",
              "```text", "Q(α) = Σ [y − P + α × (P − 1)]²",
              "dQ/dα = 2 × Σ [(P − 1) × (y − P + α × (P − 1))] = 0",
              "α̂ = Σ [(P − 1) × (P − y)] / Σ [(P − 1)²]", "```", "",
              f"I obtained **α̂ = {result['alpha_observed']:.12f}** and:", "", "```text",
              f"Sfit(P) = {1-result['alpha_observed']:.12f} × P + {result['alpha_observed']:.12f}",
              "RMSE = √(sum of squared residuals / number of worker counts)", "```", "",
              f"RMSE is **{result['rmse']:.6f}** and descriptive R² is **{result['r_squared']:.6f}**. "
              f"The residual-based standard error of α̂ is **{result['alpha_residual_standard_error']:.6f}** "
              "(n − 1 degrees of freedom). This assumes independent, equal-variance errors; "
              "it is not a calibrated confidence interval for these variable measurements.", "",
              f"An unrestricted line gives S = {result['free_intercept_diagnostic']['slope']:.6f} × P "
              f"+ {result['free_intercept_diagnostic']['intercept']:.6f}; I kept the required Gustafson fit.",
              "", "## Conclusion", "",
              "The fitted α̂ is an **effective overhead parameter**, not an instrumented serial-code fraction. "
              "I did not clamp its estimate to [0, 1]. The model forces S(1) = 1, but the measured "
              f"one-worker path includes spawn overhead. Its residual is {result['residuals'][0]['residual']:.6f}; it affects fit "
              "diagnostics but not α̂ because P − 1 = 0.", "",
              "Runtime increased rather than remaining constant. I retained the noisy P = 6 trials "
              "and did not attribute the variation to unmeasured thermal or NUMA effects.", "",
              "[Raw trials](../benchmarks/results.csv) · [All means, SD and SE](../benchmarks/summary.csv) · "
              "[Fit and residuals](../benchmarks/fit.json) · [Session metadata](../benchmarks/results.metadata.json) · "
              "[Hardware and plot](task24_hardware_audit.md).", "",
              "My report is regenerated by `report_results.py`; the absolute-path commands are in "
              "the [submission README](../README.md#reproduction).", ""]
    output = ROOT / "analysis" / "task23_experimental_results.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(output)


if __name__ == "__main__":
    main()