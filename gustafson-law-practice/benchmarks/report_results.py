              "This is a one-parameter constrained-form regression: its extrapolated line is `S=(1-alpha)P+alpha`, hence S(1)=1. The estimate is **not clamped** to [0,1]; a nonphysical fit would be explicitly flagged. No runtime fraction is directly instrumented.", "",
